/* =====================================================================
 * PDFs: SAMPLE e-ticket (until Tripgic is live) and the payment invoice.
 * Shared look: dark header band with the SKYO logo mark, clean tables.
 * ===================================================================== */

const W = 595;
const H = 842;
const C = {
  ink: rgb(0.04, 0.06, 0.12), muted: rgb(0.42, 0.45, 0.5), line: rgb(0.89, 0.9, 0.93), soft: rgb(0.965, 0.97, 0.985),
  blue: rgb(0, 0.34, 1), orange: rgb(1, 0.35, 0.12), green: rgb(0.05, 0.6, 0.35), white: rgb(1, 1, 1), night: rgb(0.04, 0.06, 0.12),
};
const GENDER: Record<string, string> = { M: "Male", F: "Female", T: "Transgender" };
const BERTH: Record<string, string> = { LB: "Lower", MB: "Middle", UB: "Upper", SL: "Side lower", SU: "Side upper" };

/** Standard fonts only cover WinAnsi — keep text printable. */
const clean = (s: string) => s.replace(/₹/g, "Rs. ").replace(/×/g, "x").replace(/→/g, "->").replace(/[–—]/g, "-").replace(/·/g, "|").replace(/[^\x20-\x7E]/g, "");
const money = (paise: number) => `Rs. ${(paise / 100).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const ist = (d: Date | string | null | undefined) =>
  d ? new Date(d).toLocaleString("en-IN", { timeZone: "Asia/Kolkata", day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit", hour12: true }) + " IST" : "-";

type Ctx = { page: PDFPage; reg: PDFFont; bold: PDFFont };

function text(c: Ctx, s: string, x: number, y: number, size = 10, font: "reg" | "bold" = "reg", color: RGB = C.ink) {
  c.page.drawText(clean(s), { x, y, size, font: font === "bold" ? c.bold : c.reg, color });
}
function textRight(c: Ctx, s: string, xRight: number, y: number, size = 10, font: "reg" | "bold" = "reg", color: RGB = C.ink) {
  const f = font === "bold" ? c.bold : c.reg;
  const t = clean(s);
  c.page.drawText(t, { x: xRight - f.widthOfTextAtSize(t, size), y, size, font: f, color });
}
/** Wraps text into lines that fit `width`. */
function wrap(f: PDFFont, s: string, size: number, width: number) {
  const words = clean(s).split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    const t = cur ? `${cur} ${w}` : w;
    if (f.widthOfTextAtSize(t, size) > width && cur) {
      lines.push(cur);
      cur = w;
    } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}

/** SKYO logo mark (same shape as the website's LogoMark) drawn as vectors. */
function logo(c: Ctx, x: number, yTop: number, size = 34) {
  c.page.drawRectangle({ x, y: yTop - size, width: size, height: size, color: rgb(0.1, 0.13, 0.24) });
  c.page.drawSvgPath("M14 40c10-2 22-10 34-22-4 10-10 20-20 26 6-1 12-3 18-7-7 9-18 13-32 3z", { x, y: yTop, scale: size / 64, color: C.orange });
}

function header(c: Ctx, site: string, title: string, right: [string, string]) {
  c.page.drawRectangle({ x: 0, y: H - 96, width: W, height: 96, color: C.night });
  c.page.drawRectangle({ x: 0, y: H - 99, width: W, height: 3, color: C.orange });
  logo(c, 36, H - 28, 38);
  text(c, site, 84, H - 50, 20, "bold", C.white);
  text(c, title, 84, H - 66, 9.5, "reg", rgb(0.78, 0.81, 0.88));
  textRight(c, right[0], W - 36, H - 48, 15, "bold", C.white);
  textRight(c, right[1], W - 36, H - 64, 9, "reg", rgb(0.78, 0.81, 0.88));
}

function footer(c: Ctx, lines: string[], tone: "warn" | "info", partner = "IRCTC / Indian Railways") {
  const h = 18 + lines.length * 13;
  c.page.drawRectangle({ x: 30, y: 46, width: W - 60, height: h, color: tone === "warn" ? rgb(1, 0.96, 0.93) : C.soft });
  lines.forEach((l, i) => text(c, l, 42, 46 + h - 18 - i * 13, i === 0 ? 8.8 : 8.3, i === 0 ? "bold" : "reg", i === 0 && tone === "warn" ? rgb(0.8, 0.3, 0.05) : C.muted));
  text(c, `Generated by SKYO | support via the Contact page | not affiliated with ${partner}`, 30, 28, 7.5, "reg", C.muted);
}

const label = (c: Ctx, s: string, x: number, y: number) => text(c, s.toUpperCase(), x, y, 7.5, "bold", C.muted);

/* ------------------------------ E-ticket ----------------------------- */

export async function ticketPdf(t: { ref: string; uid: string; details: TrainBookingDetails; amount: number; paymentId: string | null; paidAt: Date | null; site?: string }) {
  const d = t.details;
  const doc = await PDFDocument.create();
  doc.setTitle(`SKYO e-Ticket ${t.ref}`);
  doc.setAuthor("SKYO");
  const page = doc.addPage([W, H]);
  const c: Ctx = { page, reg: await doc.embedFont(StandardFonts.Helvetica), bold: await doc.embedFont(StandardFonts.HelveticaBold) };
  header(c, t.site || "SKYO", "Electronic Reservation Slip (ERS)", [`PNR ${d.ticket?.pnr ?? "-"}`, `Booking ${t.ref}`]);
  page.drawText("SAMPLE - NOT VALID FOR TRAVEL", { x: 62, y: 250, size: 32, font: c.bold, color: C.orange, opacity: 0.1, rotate: degrees(30) });

  // journey card
  let y = H - 130;
  page.drawRectangle({ x: 30, y: y - 92, width: W - 60, height: 100, color: C.soft });
  text(c, `${d.train.number}  ${d.train.name}`, 44, y - 14, 14, "bold");
  text(c, d.from, 44, y - 46, 24, "bold", C.blue);
  page.drawLine({ start: { x: 125, y: y - 38 }, end: { x: 250, y: y - 38 }, thickness: 1.2, color: rgb(0.75, 0.78, 0.85), dashArray: [3, 3] });
  text(c, d.to, 262, y - 46, 24, "bold", C.blue);
  text(c, `Journey ${fmtDate(d.date)}`, 44, y - 66, 9.5, "reg", C.muted);
  text(c, `Class ${d.cls} | Quota ${d.quota} | Food ${d.food ? "included" : "not opted"}`, 44, y - 80, 9.5, "reg", C.muted);
  label(c, "Chart", 400, y - 18);
  text(c, d.ticket?.chartStatus ?? "-", 400, y - 32, 10, "bold");
  label(c, "Auto upgradation", 400, y - 52);
  text(c, d.autoUpgrade === false ? "Not opted" : "Considered", 400, y - 66, 10, "bold");

  // passengers
  y -= 124;
  page.drawRectangle({ x: 30, y: y - 7, width: W - 60, height: 22, color: C.night });
  const cols = [40, 62, 230, 268, 335, 420];
  ["#", "Passenger", "Age", "Gender", "Status", "Coach / berth"].forEach((h, i) => text(c, h, cols[i], y, 8.5, "bold", C.white));
  y -= 24;
  (d.ticket?.allocations || []).forEach((a, i) => {
    if (i % 2) page.drawRectangle({ x: 30, y: y - 7, width: W - 60, height: 20, color: C.soft });
    text(c, String(i + 1), cols[0], y, 10);
    text(c, a.name, cols[1], y, 10, "bold");
    text(c, String(a.age), cols[2], y, 10);
    text(c, GENDER[a.gender] || a.gender, cols[3], y, 10);
    text(c, a.status, cols[4], y, 10, "bold", a.status === "CNF" ? C.green : C.orange);
    text(c, a.coach ? `${a.coach} / ${a.berth} ${BERTH[a.berthType ?? ""] ?? a.berthType ?? ""}` : "-", cols[5], y, 10);
    y -= 20;
  });

  // fare summary
  y -= 16;
  label(c, "Fare summary", 36, y);
  y -= 6;
  const lines = d.charges?.lines ?? [{ key: "fare", label: "Total fare", paise: Math.round(t.amount * 100) }];
  for (const l of lines) {
    y -= 15;
    text(c, l.label, 36, y, 9.5, "reg", C.muted);
    textRight(c, l.paise < 0 ? `- ${money(-l.paise)}` : money(l.paise), W - 36, y, 9.5, "reg", l.paise < 0 ? C.green : C.ink);
  }
  y -= 8;
  page.drawLine({ start: { x: 36, y }, end: { x: W - 36, y }, thickness: 0.8, color: C.line });
  y -= 18;
  text(c, "Total paid", 36, y, 12, "bold");
  textRight(c, money(Math.round(t.amount * 100)), W - 36, y, 12, "bold");
  y -= 22;
  text(c, `Payment ${t.paymentId ?? "-"} | ${ist(t.paidAt)}`, 36, y, 8.5, "reg", C.muted);
  y -= 12;
  text(c, `Ticket no. ${d.ticket?.ticketNo ?? "-"} | issued via ${d.ticket?.provider ?? "-"} | SKYO ID ${t.uid}${d.insurance?.opted ? " | travel insurance opted" : ""}`, 36, y, 8.5, "reg", C.muted);

  footer(c, ["This is a SAMPLE ticket generated in test mode (Tripgic mock). It is NOT valid for travel.", "Carry a valid photo ID. Check train status before you leave. Live data by RailCore."], "warn");
  return doc.save();
}

/* --------------------------- Flight e-ticket -------------------------- */

const fmtMin = (m: number) => `${Math.floor(m / 60)}h ${String(m % 60).padStart(2, "0")}m`;

export async function flightTicketPdf(t: { ref: string; uid: string; details: FlightBookingDetails; amount: number; paymentId: string | null; paidAt: Date | null; site?: string }) {
  const d = t.details;
  const f = d.flight;
  const doc = await PDFDocument.create();
  doc.setTitle(`SKYO Flight e-Ticket ${t.ref}`);
  doc.setAuthor("SKYO");
  const page = doc.addPage([W, H]);
  const c: Ctx = { page, reg: await doc.embedFont(StandardFonts.Helvetica), bold: await doc.embedFont(StandardFonts.HelveticaBold) };
  header(c, t.site || "SKYO", `Flight e-ticket | ${d.cls} | ${d.passengers.length} traveller${d.passengers.length > 1 ? "s" : ""}`, [`PNR ${d.ticket?.pnr ?? "-"}`, `Booking ${t.ref}`]);
  page.drawText("SAMPLE - NOT VALID FOR TRAVEL", { x: 62, y: 250, size: 32, font: c.bold, color: C.orange, opacity: 0.1, rotate: degrees(30) });

  let y = H - 122;
  // one boarding-pass style card per segment
  f.legs.forEach((l, i) => {
    const h = 104;
    page.drawRectangle({ x: 30, y: y - h, width: W - 60, height: h, color: C.soft });
    page.drawRectangle({ x: 30, y: y - h, width: 5, height: h, color: C.blue });
    text(c, `${l.airline.name}  |  ${l.airline.iata} ${l.number}`, 46, y - 18, 11, "bold");
    textRight(c, `${l.aircraft.name}${d.ticket?.airlinePnrs?.[l.key] ? `  |  Airline PNR ${d.ticket.airlinePnrs[l.key]}` : ""}`, W - 44, y - 18, 8.5, "reg", C.muted);
    text(c, l.from.time, 46, y - 50, 22, "bold");
    text(c, `${l.from.iata}  ${l.from.city}`, 46, y - 66, 9.5, "bold", C.blue);
    text(c, `${l.from.airport}`.slice(0, 40), 46, y - 79, 8, "reg", C.muted);
    text(c, `Terminal ${l.from.terminal || "-"}`, 46, y - 91, 8, "reg", C.muted);
    page.drawLine({ start: { x: 220, y: y - 44 }, end: { x: 360, y: y - 44 }, thickness: 1.1, color: rgb(0.7, 0.74, 0.82), dashArray: [3, 3] });
    page.drawSvgPath("M0 0 L10 4 L0 8 L2 4 Z", { x: 286, y: y - 40, scale: 1, color: C.blue });
    text(c, fmtMin(l.durationMin), 266, y - 60, 8.5, "bold", C.muted);
    text(c, `${fmtDate(i === 0 ? d.date : d.date)}${l.dayOffset ? " (+1 day arrival)" : ""}`, 240, y - 74, 8, "reg", C.muted);
    textRight(c, l.to.time, W - 44, y - 50, 22, "bold");
    textRight(c, `${l.to.iata}  ${l.to.city}`, W - 44, y - 66, 9.5, "bold", C.blue);
    textRight(c, `${l.to.airport}`.slice(0, 40), W - 44, y - 79, 8, "reg", C.muted);
    textRight(c, `Terminal ${l.to.terminal || "-"}`, W - 44, y - 91, 8, "reg", C.muted);
    y -= h + 8;
    if (i < f.legs.length - 1) {
      text(c, `Layover in ${l.to.city} (${l.to.iata})  |  ${fmtMin(f.layovers[i] ?? 0)}  |  re-check baggage if your airlines differ`, 46, y - 6, 8.5, "bold", C.orange);
      y -= 20;
    }
  });

  // travellers
  y -= 10;
  page.drawRectangle({ x: 30, y: y - 7, width: W - 60, height: 22, color: C.night });
  const cols = [40, 62, 210, 252, 300, 420];
  ["#", "Traveller", "Age", "Type", "Seat(s)", "E-ticket no."].forEach((h, i) => text(c, h, cols[i], y, 8.5, "bold", C.white));
  y -= 24;
  (d.ticket?.allocations || []).forEach((a, i) => {
    if (i % 2) page.drawRectangle({ x: 30, y: y - 7, width: W - 60, height: 20, color: C.soft });
    text(c, String(i + 1), cols[0], y, 10);
    text(c, `${a.name} (${GENDER[a.gender]?.[0] ?? a.gender})`, cols[1], y, 10, "bold");
    text(c, String(a.age), cols[2], y, 10);
    text(c, a.type === "child" ? "Child" : "Adult", cols[3], y, 10);
    text(c, Object.values(a.seats).join(" / "), cols[4], y, 10, "bold", C.green);
    text(c, a.eticket, cols[5], y, 9.5);
    y -= 20;
  });

  // baggage & fare
  y -= 12;
  label(c, "Baggage per traveller", 36, y);
  label(c, "Fare summary", 320, y);
  const bag = f.baggage[f.cabin];
  text(c, `Cabin ${bag.cabin}  |  Check-in ${bag.checkIn}`, 36, y - 15, 9.5, "bold");
  text(c, f.refundable ? "Refundable fare (airline cancellation fee applies)" : "Saver fare: cancellation fee applies, partly refundable", 36, y - 28, 8.5, "reg", C.muted);
  text(c, "Web check-in opens 48 h before departure. Gate closes 25 min before.", 36, y - 41, 8.5, "reg", C.muted);
  let fy = y - 15;
  for (const l of d.charges?.lines ?? []) {
    text(c, l.label.slice(0, 34), 320, fy, 8.5, "reg", C.muted);
    textRight(c, l.paise < 0 ? `- ${money(-l.paise)}` : money(l.paise), W - 36, fy, 8.5, "reg", l.paise < 0 ? C.green : C.ink);
    fy -= 12;
  }
  fy -= 6;
  page.drawLine({ start: { x: 320, y: fy + 4 }, end: { x: W - 36, y: fy + 4 }, thickness: 0.8, color: C.line });
  text(c, "Total paid", 320, fy - 10, 11, "bold");
  textRight(c, money(Math.round(t.amount * 100)), W - 36, fy - 10, 11, "bold");
  y = Math.min(y - 60, fy - 30);
  text(c, `Payment ${t.paymentId ?? "-"} | ${ist(t.paidAt)}`, 36, y, 8.5, "reg", C.muted);
  text(c, `Ticket ${d.ticket?.ticketNo ?? "-"} | issued via ${d.ticket?.provider ?? "-"} | SKYO ID ${t.uid}${d.insurance?.opted ? " | travel insurance opted" : ""}`, 36, y - 12, 8.5, "reg", C.muted);

  footer(c, ["This is a SAMPLE ticket generated in test mode (Tripgic mock). It is NOT valid for travel.", "Carry a government photo ID. Schedules from aviationstack - check the live status before you leave."], "warn", "the airlines");
  return doc.save();
}

/* ------------------------------- Invoice ----------------------------- */

export async function invoicePdf(t: {
  ref: string; uid: string; details: TrainBookingDetails | FlightBookingDetails; amountPaise: number; paymentId: string | null; orderId: string | null; method: string | null;
  paidAt: Date | null; createdAt: Date; site: string; supportEmail: string;
  refunds?: { refundId: string | null; amountPaise: number; status: string; at: Date }[];
}) {
  const d = t.details as TrainBookingDetails;
  const fl = (t.details as FlightBookingDetails).kind === "flight";
  const doc = await PDFDocument.create();
  doc.setTitle(`SKYO Invoice ${t.ref}`);
  doc.setAuthor("SKYO");
  const page = doc.addPage([W, H]);
  const c: Ctx = { page, reg: await doc.embedFont(StandardFonts.Helvetica), bold: await doc.embedFont(StandardFonts.HelveticaBold) };
  header(c, t.site, d.gst ? "Tax invoice (B2B)" : "Payment receipt / invoice", [`INV-${t.ref.slice(3)}`, `Dated ${ist(t.paidAt || t.createdAt)}`]);

  // billed to / booking
  let y = H - 130;
  label(c, "Billed to", 36, y);
  label(c, "Booking", 330, y);
  y -= 16;
  const left: [string, "bold" | "reg"][] = d.gst
    ? [[d.gst.company, "bold"], [`GSTIN ${d.gst.gstin}`, "reg"], ...wrap(c.reg, d.gst.address || "", 9, 260).map((l) => [l, "reg"] as [string, "reg"]), [[d.gst.state, d.gst.pincode].filter(Boolean).join(" - "), "reg"]]
    : [[d.contact.name || "Traveller", "bold"], [`SKYO ID ${t.uid}`, "reg"], [d.contact.phone || "", "reg"], [d.contact.email || "", "reg"], [[d.billing?.address, d.billing?.state, d.billing?.pincode].filter(Boolean).join(", "), "reg"]];
  let ly = y;
  for (const [s, f] of left.filter(([s]) => s)) {
    text(c, s, 36, ly, f === "bold" ? 11 : 9, f, f === "bold" ? C.ink : C.muted);
    ly -= f === "bold" ? 15 : 12;
  }
  const right: [string, string][] = [
    ["Booking ref", t.ref], ["PNR", d.ticket?.pnr ?? "-"], [fl ? "Flight" : "Train", `${d.train.number} ${fl ? "" : d.train.name}`.trim().slice(0, 34)], ["Route", `${d.from} -> ${d.to}`],
    ["Journey", fmtDate(d.date)], [fl ? "Cabin" : "Class", `${d.cls} | ${d.pricing.count} ${fl ? "traveller" : "passenger"}${d.pricing.count > 1 ? "s" : ""}`],
  ];
  let ry = y;
  for (const [k, v] of right) {
    text(c, k, 330, ry, 9, "reg", C.muted);
    textRight(c, v, W - 36, ry, 9, "bold");
    ry -= 13;
  }

  // charges table
  y = Math.min(ly, ry) - 22;
  page.drawRectangle({ x: 30, y: y - 7, width: W - 60, height: 22, color: C.night });
  text(c, "Description", 40, y, 8.5, "bold", C.white);
  textRight(c, "Amount", W - 40, y, 8.5, "bold", C.white);
  y -= 22;
  const lines = d.charges?.lines ?? [{ key: "fare", label: "Ticket fare", paise: t.amountPaise }];
  lines.forEach((l, i) => {
    if (i % 2) page.drawRectangle({ x: 30, y: y - 7, width: W - 60, height: 20, color: C.soft });
    text(c, l.label + (l.note && ["fare", "agent_fee", "insurance", "seats"].includes(l.key) ? `  (${l.note})` : ""), 40, y, 9.5);
    textRight(c, l.paise < 0 ? `- ${money(-l.paise)}` : money(l.paise), W - 40, y, 9.5, "reg", l.paise < 0 ? C.green : C.ink);
    y -= 20;
  });
  page.drawRectangle({ x: 30, y: y - 10, width: W - 60, height: 28, color: rgb(1, 0.95, 0.91) });
  text(c, `Total paid (${t.site} total)`, 40, y, 12, "bold");
  textRight(c, money(t.amountPaise), W - 40, y, 12, "bold", C.orange);

  // GST note
  y -= 34;
  const gstTotal = (d.charges?.lines ?? []).filter((l) => l.key.endsWith("_gst")).reduce((a, l) => a + l.paise, 0);
  const custState = d.gst?.state || stateByCode(d.gst?.gstin?.slice(0, 2) || "") || d.billing?.state || null;
  label(c, "GST", 36, y);
  y -= 14;
  text(c, `GST included in this invoice: ${money(gstTotal)}${custState ? ` | place of supply: ${custState}` : ""}`, 36, y, 9);
  y -= 12;
  text(c, d.gst ? "GST details supplied by the customer for input tax credit." : "No GSTIN supplied - this receipt can be used together with the e-ticket as the invoice.", 36, y, 8.5, "reg", C.muted);

  // payment
  y -= 26;
  label(c, "Payment", 36, y);
  y -= 14;
  const pay: [string, string][] = [
    ["Gateway", "Razorpay"], ["Method", (t.method || "-").toUpperCase()], ["Payment ID", t.paymentId ?? "-"], ["Order ID", t.orderId ?? "-"], ["Paid at", ist(t.paidAt)], ["Booked at", ist(t.createdAt)],
  ];
  pay.forEach(([k, v], i) => {
    const x = i % 2 ? 310 : 36;
    if (i % 2 === 0 && i) y -= 13;
    text(c, k, x, y, 9, "reg", C.muted);
    text(c, v, x + 66, y, 9, "bold");
  });

  const refunds = (t.refunds ?? []).filter((r) => r.status !== "failed");
  if (refunds.length) {
    y -= 26;
    label(c, "Refunds", 36, y);
    for (const r of refunds) {
      y -= 14;
      text(c, `${r.refundId ?? "-"} | ${r.status === "processed" ? "credited" : "in progress (5-7 working days)"} | ${ist(r.at)}`, 36, y, 9, "reg", C.muted);
      textRight(c, `- ${money(r.amountPaise)}`, W - 36, y, 9, "bold", C.green);
    }
    const refunded = refunds.filter((r) => r.status === "processed").reduce((a, r) => a + r.amountPaise, 0);
    y -= 18;
    text(c, "Net amount after credited refunds", 36, y, 10.5, "bold");
    textRight(c, money(Math.max(0, t.amountPaise - refunded)), W - 36, y, 10.5, "bold");
  }

  footer(c, [
    "Test-mode document (sample ticket via Tripgic mock).",
    `Fare components are collected on behalf of ${fl ? "the airline" : "IRCTC"}; ${t.site}'s service fee and gateway charges are listed separately.`,
    `Questions? Write to ${t.supportEmail} and quote ${t.ref}.`,
  ], "info", fl ? "the airlines" : undefined);
  return doc.save();
}
